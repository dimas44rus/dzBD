DROP TABLE IF EXISTS tickets CASCADE;
DROP TABLE IF EXISTS screenings CASCADE;
DROP TABLE IF EXISTS seats CASCADE;
DROP TABLE IF EXISTS customers CASCADE;
DROP TABLE IF EXISTS films CASCADE;
DROP TABLE IF EXISTS halls CASCADE;

CREATE TABLE films (
    film_id         integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title           varchar(150) NOT NULL,
    genre           varchar(50) NOT NULL,
    duration_minutes integer NOT NULL CHECK (duration_minutes BETWEEN 1 AND 400),
    age_rating      integer NOT NULL CHECK (age_rating IN (0, 6, 12, 16, 18)),
    release_year    integer NOT NULL CHECK (release_year BETWEEN 1895 AND 2100),
    description     varchar(500)
);

CREATE TABLE halls (
    hall_id     integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    hall_name   varchar(50) NOT NULL UNIQUE,
    seat_count  integer NOT NULL CHECK (seat_count BETWEEN 1 AND 300)
);

CREATE TABLE seats (
    seat_id      integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    hall_id      integer NOT NULL REFERENCES halls(hall_id) ON DELETE CASCADE,
    seat_number  integer NOT NULL CHECK (seat_number > 0),
    CONSTRAINT uq_seats_hall_number UNIQUE (hall_id, seat_number),
    -- Нужен для составного внешнего ключа таблицы tickets.
    CONSTRAINT uq_seats_id_hall UNIQUE (seat_id, hall_id)
);

CREATE TABLE customers (
    customer_id  integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    first_name   varchar(80) NOT NULL,
    last_name    varchar(80) NOT NULL,
    email        varchar(150) NOT NULL UNIQUE,
    phone        varchar(30),
    registered_at timestamp NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE screenings (
    screening_id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    film_id      integer NOT NULL REFERENCES films(film_id) ON DELETE RESTRICT,
    hall_id      integer NOT NULL REFERENCES halls(hall_id) ON DELETE RESTRICT,
    starts_at    timestamp NOT NULL,
    ticket_price numeric(8, 2) NOT NULL CHECK (ticket_price > 0),
    CONSTRAINT uq_screenings_hall_start UNIQUE (hall_id, starts_at),
    -- Составной уникальный ключ позволяет гарантировать, что билет
    -- относится к месту именно того зала, где проходит сеанс.
    CONSTRAINT uq_screenings_id_hall UNIQUE (screening_id, hall_id)
);

CREATE TABLE tickets (
    ticket_id    integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    screening_id integer NOT NULL,
    hall_id      integer NOT NULL,
    seat_id      integer NOT NULL,
    customer_id  integer NOT NULL REFERENCES customers(customer_id) ON DELETE RESTRICT,
    status       varchar(12) NOT NULL DEFAULT 'Purchased'
                 CHECK (status IN ('Purchased', 'Cancelled')),
    purchased_at timestamp NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_tickets_screening_hall
        FOREIGN KEY (screening_id, hall_id)
        REFERENCES screenings(screening_id, hall_id) ON DELETE RESTRICT,
    CONSTRAINT fk_tickets_seat_hall
        FOREIGN KEY (seat_id, hall_id)
        REFERENCES seats(seat_id, hall_id) ON DELETE RESTRICT
);

-- Для одного сеанса место может иметь не более одного действующего билета.
-- После отмены билет остаётся в истории, а место можно продать повторно.
CREATE UNIQUE INDEX ux_tickets_active_seat
    ON tickets(screening_id, seat_id)
    WHERE status = 'Purchased';

CREATE INDEX ix_tickets_customer ON tickets(customer_id);
CREATE INDEX ix_tickets_screening_status ON tickets(screening_id, status);
CREATE INDEX ix_screenings_starts_at ON screenings(starts_at);

